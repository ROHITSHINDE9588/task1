# This is a basic calculator program in Python

# Step 1: Define two numbers
num1 = 100   # First number
num2 = 500    # Second number

# Step 2: Perform addition
addition = num1 + num2   # Adds num1 and num2

# Step 3: Perform subtraction
subtraction = num1 - num2   # Subtracts num2 from num1

# Step 4: Perform multiplication
multiplication = num1 * num2   # Multiplies num1 and num2

# Step 5: Perform division
division = num1 / num2   # Divides num1 by num2

# Step 6: Display results
print("Addition:", addition)         # Prints the result of addition
print("Subtraction:", subtraction)   # Prints the result of subtraction
print("Multiplication:", multiplication) # Prints the result of multiplication
print("Division:", division)         # Prints the result of division
